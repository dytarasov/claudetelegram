"""Справка."""
from __future__ import annotations

from aiogram import Router
from aiogram.filters import Command
from aiogram.types import Message
from dishka.integrations.aiogram import FromDishka

from ...infrastructure.telegram import ui
from ...infrastructure.telegram.sender import MessageSender

router = Router(name="help")

HELP = """<b>Claude Code в Telegram</b>

Всё доступно кнопками: <b>/menu</b> открывает корень, оттуда — сессия, память,
код, цели, напоминания и логи. Экраны обновляются на месте, набирать команды
повторно не нужно. Там, где нужен текст (поиск, заметка, цель, напоминание),
кнопка спросит и подождёт ответа.

Команды ниже никуда не делись — набрать быстрее, чем идти по экранам, — но
помнить их наизусть больше не обязательно.

Пиши текстом или наговаривай голосовое — всё уходит в одну непрерывную сессию
Claude Code на этом сервере, с полным доступом к нему.

<b>Разговор</b>
/ctx — расход контекста
/compact [что сохранить] — свернуть контекст, не теряя нить
/status — процесс, сессия, модель, токены, здоровье
/stop — прервать текущий ход
/new — начать сессию с чистого листа
/cd &lt;путь&gt; — сменить рабочую директорию
/model &lt;opus|sonnet|fable&gt; — сменить модель
/get &lt;путь&gt; — прислать файл с сервера
/restart — перезапустить процесс, сохранив контекст

<b>Самодопил</b>
Я правлю собственный код, проверяю его и перезапускаюсь сам. Если новая версия
не оживает — сторож снаружи возвращает прошлую без твоего участия.
/versions — версии кода: где сейчас, где stable, чем кончились выкатки
/rollback [stable|код|N] — вернуться назад (по умолчанию на stable)
/stable — считать текущую версию стабильной
/diag — здоровье: пульс, БД, Telegram, последняя выкатка

<b>Цели — работа без тебя</b>
/goal что сделать | когда считать законченным
/goals — что в работе, с паузой и снятием
Просыпаюсь по расписанию, делаю шаг, отчитываюсь сюда. Ночью не работаю,
необратимого без спроса не делаю, при исчерпании бюджета останавливаюсь.

<b>Напоминания</b>
Пиши как удобно — время выну из фразы сам.
/remind через 20 минут проверить выкатку
/remind каждый день в 9 отчёт
/todo — что висит · /done 12 — закрыть · /drop 12 — снять
Ночью (23:00–08:00) молчу, всё переносится на утро.

<b>Логи</b>
/logs [n] [слово] — последние события, можно с фильтром
/logs подробно 50 — технический лог вместо ленты
/errors — только то, что пошло не так
/logfile [события|подробно|сторож] — прислать файлом
/logsize — размеры логов

<b>Память</b>
/recall &lt;запрос&gt; — поиск по прошлым разговорам
/note &lt;текст&gt; — записать вывод на будущее
/notes [запрос] — показать заметки
/stats — сколько ходов, токенов и денег
/terms — словарь расшифровки голосовых
/term Claude Code = клауди код — научить словарь

Файлы и фото просто пересылай — они лягут в <code>uploads/</code>, и я получу
путь к ним."""


@router.message(Command("start", "help"))
async def cmd_help(message: Message, sender: FromDishka[MessageSender]) -> None:
    # Под справкой — вход в кнопочный интерфейс: читать про кнопки и не иметь
    # их под рукой было бы издевательством.
    await sender.send(message.chat.id, HELP, reply_markup=ui.keyboard(
        [ui.button("Открыть меню", "ui:menu", ui.PRIMARY)]))
