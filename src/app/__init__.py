"""Телеграм-мост к Claude Code, разложенный по слоям.

Зачем слои. Раньше весь бот жил в одном 30-килобайтном bot.py, где хендлер
Telegram сам лез в процесс claude, сам форматировал HTML и сам писал файлы.
Любая правка трогала всё сразу, а проверить кусок в отрыве было нельзя.

Теперь так (стрелка — «зависит от», внутрь, никогда наружу):

    presentation  ──►  services  ──►  domain (модели, DTO, порты)
                            │
                            ▼
                    infrastructure ──► внешний мир (Postgres, git, systemd,
                                       процесс claude, Telegram API, STT)

  • domain          — чистые данные и интерфейсы (ports). Ни одного импорта
                      aiogram/asyncpg. Это то, о чём система «думает».
  • services        — бизнес-логика: провести ход, выкатить версию, откатиться.
                      Знают только про domain и порты, а не про то, что за ними.
  • infrastructure  — реализации портов: asyncpg-репозитории, обёртки над git и
                      systemd, процесс claude, распознавание речи.
  • presentation    — aiogram: роутеры, мидлвари, вьюхи. Тонкий слой, который
                      только переводит апдейт в вызов сервиса и обратно.

Связывает всё dishka (app/di.py) — контейнер знает, какую реализацию подставить
под какой порт. Поэтому в тестах вместо Postgres подставляется словарь, а вместо
claude — заглушка, и ничего в сервисах менять не нужно.
"""
