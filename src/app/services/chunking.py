"""Нарезка текста на куски для поиска. Чистая функция, никакого ввода-вывода.

Зачем именно так, а не «каждые N символов». Разрез посреди фразы портит оба
куска: в первом мысль обрывается, во втором начинается ниоткуда, и вектор у
обоих получается смазанный. Поэтому режем по естественным швам, от крупных к
мелким: пустая строка, перевод строки, конец предложения. Жёсткий разрез по
длине остаётся крайним случаем — для сплошной простыни без единого знака.

Про перекрытие. Соседние куски делят небольшой хвост. Это стоит несколько
процентов места и спасает от типичной потери: мысль, начатая в конце одного
куска и законченная в начале другого, иначе не находится ни по одному из них.

Размеры выбраны под то, как я пишу. Абзац — 300-900 символов, значит кусок в
1200 обычно вмещает две-три законченные мысли, и это тот масштаб, на котором
поиск отвечает «вот здесь про это», а не «был такой длинный разговор».
"""
from __future__ import annotations

import re

TARGET = 1200        # к чему стремимся
MAX = 1800           # выше этого режем принудительно
MIN_TAIL = 200       # хвост короче — приклеиваем к предыдущему куску
OVERLAP = 150        # сколько символов конца повторить в начале следующего

# Швы в порядке убывания «крупности». Ищем самый крупный, который попадает в
# допустимое окно; так абзац не рвётся ради красивой длины.
_SEAMS = (
    re.compile(r"\n\s*\n"),                    # граница абзацев
    re.compile(r"\n"),                         # перевод строки
    re.compile(r"(?<=[.!?…])\s+(?=[«\"A-ZА-ЯЁ])"),  # конец предложения
    re.compile(r"(?<=[.!?…;])\s+"),            # конец предложения попроще
)


def split(text: str, target: int = TARGET, maximum: int = MAX) -> list[str]:
    """Разрезать текст на куски. Короткий текст возвращается одним куском."""
    text = (text or "").strip()
    if not text:
        return []
    if len(text) <= maximum:
        return [text]

    pieces: list[str] = []
    rest = text
    while len(rest) > maximum:
        cut = _find_seam(rest, target, maximum)
        piece = rest[:cut].strip()
        if piece:
            pieces.append(piece)
        # Назад на величину перекрытия, но не дальше начала уже отрезанного:
        # иначе на коротких кусках цикл затопчется на месте.
        step = max(cut - OVERLAP, cut // 2, 1)
        rest = rest[step:].lstrip()

    tail = rest.strip()
    if tail:
        if pieces and len(tail) < MIN_TAIL:
            # Огрызок в 50 символов сам по себе бесполезен для поиска: у него
            # нет контекста, и вектор у него случайный.
            pieces[-1] = f"{pieces[-1]}\n{tail}"
        else:
            pieces.append(tail)
    return pieces


def _find_seam(text: str, target: int, maximum: int) -> int:
    """Где резать: ближайший к target шов внутри окна, иначе жёстко по maximum.

    Окно начинается с половины target, чтобы не рождать заведомо мелкие куски
    из-за первого попавшегося перевода строки.
    """
    window_start, window_end = target // 2, min(maximum, len(text))
    for seam in _SEAMS:
        best = None
        for match in seam.finditer(text, window_start, window_end):
            best = match.end()          # ищем последний шов до конца окна,
            if best >= target:          # но не дальше цели, если она достигнута
                break
        if best:
            return best
    return maximum


def chunk_turn(prompt: str, answer: str) -> list[tuple[str, str]]:
    """Куски одного хода: (роль, текст).

    Вопрос и ответ режутся раздельно и намеренно. Склеенные, они дают вектор
    «где-то посередине между вопросом и ответом» — то есть не похожий ни на
    формулировку человека, ни на суть ответа.
    """
    out: list[tuple[str, str]] = []
    out += [("user", piece) for piece in split(prompt)]
    out += [("assistant", piece) for piece in split(answer)]
    return out
