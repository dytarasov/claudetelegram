@runtime_checkable
class Embedder(Protocol):
    """Векторизация текста для семантического поиска.

    Отдельный порт от LLMClient: эмбеддинги — другой протокол (свой эндпоинт,
    батчи, размерность) и, вообще говоря, другой провайдер. Сейчас за обоими
    портами стоит OpenRouter, но увести векторы к кому-то ещё должно быть можно,
    не трогая чат-модель.

    Без ключа в контейнере стоит NullEmbedder: он честно говорит «не умею», и
    поиск по журналу вырождается в полнотекстовый.
    """

    def available(self) -> bool: ...
    def dimensions(self) -> int:
        """Длина вектора. Должна совпадать с типом колонки в БД."""
        ...
    def model_name(self) -> str: ...
    async def embed(self, texts: Sequence[str]) -> list[list[float]]: ...


class LLMClient(Protocol):
    """Языковая модель общего назначения — для вспомогательных задач.

    Это не тот claude, что ведёт разговор: тот живёт отдельным процессом и держит
    контекст. Здесь — короткие служебные вызовы без истории: подсказать, что
    услышалось в кривой расшифровке, сжать длинный ход в одну строку, разметить
    заметку. Порт нарочно провайдер-независимый: сегодня за ним OpenRouter,
    завтра что угодно другое.
    """

    def available(self) -> bool: ...
    def default_model(self) -> str: ...
    async def complete(self, prompt: str, *, system: str | None = None,
                       model: str | None = None, max_tokens: int = 1024,
                       temperature: float = 0.2) -> LLMReply: ...


class Notifier(Protocol):
    """Разговор с чатом со стороны сервиса.

    Нужен тем, кто говорит сам, без входящего апдейта: ход из очереди завершился,
    процесс claude умер, выкатка доехала. Через порт — чтобы сервис не знал ни
    про aiogram, ни про HTML-разметку сообщений.
    """

    async def send(self, chat_id: int, html: str) -> None: ...
    async def send_error(self, chat_id: int, title: str, detail: str) -> None:
        """Сообщить о сбое. Экранирование текста — забота реализации."""
        ...
    async def send_actions(self, chat_id: int, html: str,
                           actions: list[tuple[str, str]]) -> object:
        """Сообщение с кнопками: всё, что бот шлёт сам, должно закрываться касанием."""
        ...
    async def typing(self, chat_id: int) -> None: ...
    async def alive(self) -> bool:
        """Отвечает ли Telegram. Нужно пульсу: бот, который не может ответить,
        здоровым не считается."""
        ...


class TurnPresenter(Protocol):
    """Показ одного хода: живое сообщение во время работы, разбор в конце.

    Отдельный порт нужен, чтобы ConversationService не зависел от Telegram.
    Он решает, что ход состоялся; как это выглядит на экране — не его дело.
    """

    async def start(self) -> None: ...
    async def on_event(self, event: dict) -> None: ...
    async def finish(self, result: dict) -> None: ...
    def close(self) -> None: ...
    @property
    def answer(self) -> str: ...
    @property
    def tools(self) -> list[str]: ...


