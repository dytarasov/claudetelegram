class AssistantProcess(Protocol):
    """Процесс `claude --print --input-format stream-json` — мой собственный мозг.

    Живёт долго, переживает ходы, умеет резюмировать сессию по id. Порт нужен,
    чтобы ConversationService можно было тестировать без запуска настоящего claude.
    """

    @property
    def alive(self) -> bool: ...
    async def start(self) -> None: ...
    async def stop(self) -> None: ...
    async def restart(self, *, fresh: bool = False) -> None: ...
    async def ask(self, text: str, on_event: Callable[[dict], Awaitable[None]]) -> dict: ...
    async def interrupt(self, timeout: float = 15.0) -> bool: ...
    def status(self) -> dict[str, Any]: ...
    def context_usage(self) -> tuple[int, int]: ...
    def set_cwd(self, path: Path) -> None:
        """Сменить рабочую директорию. Применится при следующем запуске процесса."""
        ...
    def set_model(self, name: str) -> None: ...


