class LogReader(Protocol):
    """Чтение собственных логов.

    Нужен, чтобы посмотреть, что происходило, прямо из чата — не заходя по SSH.
    Порт, а не прямая работа с файлами, по обычной причине: сервис не должен
    знать, лежит лог файлом, в journald или где-то ещё.
    """

    def streams(self) -> list[str]: ...
    def tail(self, stream: str, limit: int, needle: str | None = None) -> list[str]: ...
    def path(self, stream: str) -> Path | None: ...
    def size(self, stream: str) -> int: ...


class StorageHealth(Protocol):
    """Живо ли хранилище. Минимальный контракт: пульсу больше ничего не нужно."""

    async def healthy(self) -> bool: ...
